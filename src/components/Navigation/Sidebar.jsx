export function getIcon(name) {
  return icons[name] || null;
}

export function Sidebar() {
  const { user } = useAuth();
  const {
    activeView,
    navigate,
    sidebarCollapsed,
    toggleSidebar,
    expandedSections,
    toggleSection,
  } = useNavigation();

  return (
    <aside
      className={`
        hidden lg:flex flex-col h-screen bg-white/10 backdrop-blur-xl border-r border-white/20
        transition-all duration-300 ease-in-out
        ${sidebarCollapsed ? 'w-20' : 'w-64'}
      `}
    >
      {/* Logo & Toggle */}
      <div className="flex items-center justify-between p-4 border-b border-white/10">
        {!sidebarCollapsed && (
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-violet-500 to-purple-600 flex items-center justify-center shadow-lg">
              <span className="text-white font-bold text-xl">F</span>
            </div>
            <span className="font-bold text-white text-lg">Flowly</span>
          </div>
        )}
        <button
          onClick={toggleSidebar}
          className="p-2 rounded-lg hover:bg-white/10 text-white/70 hover:text-white transition-colors"
        >
          {sidebarCollapsed ? getIcon('chevronRight') : getIcon('chevronLeft')}
        </button>
      </div>

      {/* Navigation */}
      <nav className="flex-1 overflow-y-auto py-4 px-3">
        {/* Home */}
        <button
          onClick={() => navigate('dashboard')}
          className={`
            w-full flex items-center gap-3 px-3 py-2.5 rounded-xl mb-2 transition-all duration-200
            ${activeView === 'dashboard'
              ? 'bg-white text-slate-800 shadow-lg'
              : 'text-white/80 hover:bg-white/10 hover:text-white'
            }
            ${sidebarCollapsed ? 'justify-center' : ''}
          `}
          title={sidebarCollapsed ? 'Home' : undefined}
        >
          {getIcon('home')}
          {!sidebarCollapsed && <span className="font-medium">Home</span>}
        </button>

        {/* Section Groups */}
        {Object.entries(NAV_SECTIONS).map(([key, section]) => {
          if (key === 'home') return null;
          return (
            <SidebarGroup
              key={key}
              section={section}
              sectionKey={key}
              collapsed={sidebarCollapsed}
              expanded={expandedSections.includes(key)}
              onToggle={() => toggleSection(key)}
              activeView={activeView}
              onNavigate={navigate}
            />
          );
        })}
      </nav>

      {/* User Profile */}
      <div className={`p-4 border-t border-white/10 ${sidebarCollapsed ? 'items-center' : ''}`}>
        <div className={`flex items-center gap-3 ${sidebarCollapsed ? 'justify-center' : ''}`}>
          {user?.photoURL ? (
            <img
              src={user.photoURL}
              alt={user.displayName}
              className="w-10 h-10 rounded-full border-2 border-white/30"
            />
          ) : (
            <div className="w-10 h-10 rounded-full bg-white/20 flex items-center justify-center text-white font-medium">
              {user?.displayName?.[0] || 'U'}
            </div>
          )}
          {!sidebarCollapsed && (
            <div className="flex-1 min-w-0">
              <p className="text-sm font-medium text-white truncate">
                {user?.displayName || 'User'}
              </p>
              <p className="text-xs text-white/60 truncate">{user?.email}</p>
            </div>
          )}
        </div>
      </div>
    </aside>
  );
}
